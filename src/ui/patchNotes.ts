/**
 * Tags d'une note de version : ils résument d'un coup d'œil les domaines touchés
 * par une mise à jour (affichés sous le titre, dans le menu principal).
 */
export type PatchTag =
  | 'villain' // nouveau vilain
  | 'animation' // décors & animations d'arrière-plan
  | 'liste-villains' // écran « Liste des villains »
  | 'atelier' // éditeur de vilains
  | 'reseau' // multijoueur
  | 'correctif' // corrections de bugs
  | 'equilibrage' // rééquilibrages de cartes/coûts/forces
  | 'ia' // comportement du bot (Fatalité, jauge d'objectif)
  | 'cartes' // nouvelles cartes / nouveaux effets (sans nouveau vilain)
  | 'regles' // moteur de règles / mécaniques de jeu
  | 'son' // musique, bruitages, voix
  | 'interface' // menus, ergonomie générale
  | 'profil' // profil joueur / avatars

